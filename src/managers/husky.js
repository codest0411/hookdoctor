import fs from "node:fs";
import path from "node:path";
import { STANDARD_GIT_HOOKS, formatDisplayPath, safeReadFile, toPosixPath } from "../sanitize.js";

const STANDARD_HOOK_SET = new Set(STANDARD_GIT_HOOKS);

/**
 * Husky v9+ manager descriptor and detector.
 * Docs: https://typicode.github.io/husky/
 */
export const huskyManager = {
  id: /** @type {const} */ ("husky"),
  name: "Husky",
  docsUrl: "https://typicode.github.io/husky/",
  setsHooksPath: true,
  userFilesNeedExecutableBit: false,

  /**
   * @param {import("./index.js").ManagerDetectionInput} input
   * @returns {import("./index.js").ManagerDetectionResult}
   */
  detect(input) {
    const { repoRoot, homeDir, pkg, hooksDir } = input;
    /** @type {string[]} */
    const evidence = [];
    /** @type {Map<string, { sourceFile: string, content: string }>} */
    const configuredHooks = new Map();

    const hasDep =
      Boolean(pkg.dependencies.husky) || Boolean(pkg.devDependencies.husky);
    if (hasDep) evidence.push("`husky` declared in package.json");

    let huskyDirExists = false;
    let huskyUnderscoreExists = false;
    if (repoRoot) {
      const huskyDir = path.join(repoRoot, ".husky");
      try {
        if (fs.statSync(huskyDir).isDirectory()) {
          huskyDirExists = true;
          evidence.push("`.husky/` directory exists");

          const entries = fs.readdirSync(huskyDir, { withFileTypes: true });
          for (const entry of entries) {
            if (entry.name === "_" && entry.isDirectory()) {
              huskyUnderscoreExists = true;
              continue;
            }
            if (!entry.isFile() || !STANDARD_HOOK_SET.has(entry.name)) continue;
            const fullPath = path.join(huskyDir, entry.name);
            const read = safeReadFile(fullPath, { allowedRoots: [repoRoot], maxBytes: 65536 });
            configuredHooks.set(entry.name, {
              sourceFile: formatDisplayPath(fullPath, repoRoot, homeDir),
              content: read.ok ? read.content : "",
            });
          }
        }
      } catch {
        // .husky missing
      }
    }

    const declared = hasDep || huskyDirExists;
    const effectivePosix = toPosixPath(hooksDir.effectiveHooksDir);
    const pointsToHuskyUnderscore =
      effectivePosix.endsWith("/.husky/_") || effectivePosix === ".husky/_";
    const pointsToHuskyRoot =
      effectivePosix.endsWith("/.husky") || effectivePosix === ".husky";

    let installed = false;
    /** @type {string[]} */
    const installEvidence = [];
    let missingInstallReason = null;

    if (declared) {
      if (pointsToHuskyUnderscore && huskyUnderscoreExists && hooksDir.effectiveDirIsDirectory) {
        installed = true;
        installEvidence.push("`core.hooksPath` points to `.husky/_` and directory exists");
      } else if (pointsToHuskyRoot && huskyDirExists && hooksDir.effectiveDirIsDirectory) {
        installed = true;
        installEvidence.push("`core.hooksPath` points to `.husky` (v8 layout) and directory exists");
      } else {
        missingInstallReason =
          "Husky is declared by the project, but `core.hooksPath` does not point to `.husky/_` (or `.husky/_` has not been generated by `husky`).";
      }
    }

    const prepare = pkg.scripts.prepare ?? "";
    const postinstall = pkg.scripts.postinstall ?? "";
    const hasInstallScript =
      prepare.includes("husky") || postinstall.includes("husky");

    return {
      id: "husky",
      name: "Husky",
      docsUrl: this.docsUrl,
      setsHooksPath: true,
      declared,
      installed,
      evidence,
      installEvidence,
      missingInstallReason,
      hasInstallScript,
      configuredHooks,
      sourcedFilesDir: pointsToHuskyUnderscore && repoRoot ? path.join(repoRoot, ".husky") : null,
    };
  },
};
